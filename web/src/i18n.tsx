export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem("lumen.lang") as Lang | null;
    if (saved && ["ru", "kk", "en"].includes(saved)) return saved;
    const nav = navigator.language?.slice(0, 2);
    return nav === "kk" ? "kk" : nav === "en" ? "en" : "ru";
  });
  const setLang = useCallback((l: Lang) => { localStorage.setItem("lumen.lang", l); setLangState(l); }, []);
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const t = useCallback((k: string, v?: Record<string, string | number>) => {
    const row = D[k];
    let s = row ? row[lang === "ru" ? 0 : lang === "kk" ? 1 : 2] : k;
    if (v) for (const [a, b] of Object.entries(v)) s = s.replace(`{${a}}`, String(b));
    return s;
  }, [lang]);
  return <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>;
}

