def test_every_phrasing_reaches_its_answer():
    wrong = []
    for text, i in CASES:
        hit = faq_match(text)
        if not hit or hit[0] != Q[i]:
            wrong.append(f"{text!r} → {hit[0] if hit else 'не понял'} (ждали {Q[i]!r})")
    assert not wrong, "\n".join(wrong)


def test_off_topic_is_not_answered_from_the_faq():
    for text in OFF_TOPIC:
        r = answer(text)
        assert r.escalate or r.source == "llm", text
