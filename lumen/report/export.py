READY = {
    "READY": "READY — можно начинать разработку и тестирование",
    "READY WITH CONDITIONS": "READY WITH CONDITIONS — можно начинать после исправлений",
    "NOT READY": "NOT READY — начинать разработку и тестирование нельзя",
    "INSUFFICIENT DATA": "INSUFFICIENT DATA — недостаточно данных для надёжной оценки",
}
SEV_HEX = {"CRITICAL": "D92D20", "HIGH": "E8620C", "MEDIUM": "C99A06", "LOW": "3B82F6", "INFO": "98A2B3"}
MODE = {"llm": "LLM + детерминированные правила", "offline": "Только правила (без LLM)", "mock": "Демо (Mock LLM)"}
EXPORT_FORMATS = ("docx", "xlsx", "pdf")
MIME = {
    "docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    "xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    "pdf": "application/pdf",
}


def _where(f: Finding) -> str:
    return f.loc.label() if f.loc else "документ в целом"


def _date(iso: str) -> str:
    try:
        return datetime.fromisoformat(iso).strftime("%d.%m.%Y %H:%M (UTC+05:00)")
    except Exception:
        return iso


def _passport_rows(r: AuditResult) -> list[tuple[str, str]]:
    p = r.passport
    return [
        ("Документ", p.document_title or p.document_name), ("Файл", f"{p.document_name} ({p.document_format})"),
        ("Дата анализа", _date(p.analysed_at)), ("Модель", f"{p.model} — {PROVIDER_LABELS.get(p.provider, p.provider)}"),
        ("Режим", MODE[p.mode]), ("Версия агента", f"LÜMEN {p.agent_version}, коммит {p.agent_commit}"),
        ("SHA-256", p.document_sha256), ("Обращений к модели", str(p.llm_calls)),
    ]


# =========================================================================== DOCX
def render_docx(r: AuditResult) -> bytes:
    import docx
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.shared import Pt, RGBColor

    d = docx.Document()
    st = d.styles["Normal"]
    st.font.name = "Calibri"
    st.font.size = Pt(10.5)

    def table(rows: list[list[str]], header: bool = True):
        t = d.add_table(rows=0, cols=len(rows[0]))
        t.style = "Light Grid Accent 1"
        for i, row in enumerate(rows):
            cells = t.add_row().cells
            for c, v in zip(cells, row):
                c.text = str(v)
                if header and i == 0:
                    for run in c.paragraphs[0].runs:
                        run.bold = True
        return t

    d.add_heading(f"Отчёт о проверке требований: «{r.passport.document_title or r.passport.document_name}»", 0)
    if r.demo:
        d.add_paragraph("ДЕМОНСТРАЦИОННЫЙ ПРОГОН — не проверка документа организаторов.").runs[0].bold = True
    v = d.add_paragraph()
    run = v.add_run(READY[r.readiness])
    run.bold = True
    run.font.size = Pt(13)
    d.add_paragraph(r.readiness_reason)
    s = r.scores
    d.add_paragraph(f"Требований: {s.total_requirements} · замечаний: {s.findings_total} (CRITICAL {s.by_severity['CRITICAL']}, "
                    f"HIGH {s.by_severity['HIGH']}, MEDIUM {s.by_severity['MEDIUM']}, LOW {s.by_severity['LOW']}) · "
                    f"вопросов: {len(r.questions)} · индекс качества {s.quality_index}/100")

    d.add_heading("1. Паспорт прогона", 1)
    table([["Параметр", "Значение"]] + [list(x) for x in _passport_rows(r)])
    for w in r.warnings:
        d.add_paragraph(f"⚠ {w}")

    d.add_heading("2. Как агент нарезал требования", 1)
    table([["ID в отчёте", "ID в документе", "Тип", "Место", "Краткая формулировка"]] +
          [[x.id, x.source_id if x.source_id_kind == "explicit" else "нет", TYPE_RU.get(x.type, x.type),
            x.loc.label(), x.summary] for x in r.requirements])

    def finding(f: Finding):
        h = d.add_paragraph()
        rr = h.add_run(f"{f.id} · {f.severity} · {f.title}" + ("" if f.status == "confirmed" else " (требует проверки)"))
        rr.bold = True
        rr.font.color.rgb = RGBColor.from_string(SEV_HEX[f.severity])
        d.add_paragraph(f"Критерий: {criterion_name(f.criterion)} ({f.standard_ref or '—'}). Где: {_where(f)}"
                        + (f"; требования: {', '.join(f.req_ids)}" if f.req_ids else ""))
        if f.quote:
            q = d.add_paragraph(f"«{f.quote}»")
            q.paragraph_format.left_indent = Pt(18)
            q.runs[0].italic = True
        for label, val in (("Что не так", f.problem), ("Риск", f.risk), ("Как исправить", f.fix),
                           ("Улучшенная формулировка", f.rewrite)):
            if val:
                p = d.add_paragraph()
                p.add_run(f"{label}: ").bold = True
                p.add_run(val)

    d.add_heading("3. Проверка каждого требования", 1)
    by_req: dict[str, list[Finding]] = {}
    for f in r.findings:
        if f.scope == "requirement" and f.req_ids:
            by_req.setdefault(f.req_ids[0], []).append(f)
    for x in r.requirements:
        fs = by_req.get(x.id)
        if not fs:
            continue
        d.add_heading(f"{x.id}{' (' + x.source_id + ')' if x.source_id_kind == 'explicit' else ''} — {x.summary}", 2)
        q = d.add_paragraph(x.quote)
        q.paragraph_format.left_indent = Pt(18)
        for f in fs:
            finding(f)

    d.add_heading("4. Проверка всего набора", 1)
    for f in [f for f in r.findings if f.scope == "set"]:
        finding(f)

    d.add_heading("5. Вопросы к владельцу требований", 1)
    for q in r.questions:
        p = d.add_paragraph()
        p.add_run(f"{q.id} ({', '.join(q.req_ids) or 'набор'}): ").bold = True
        p.add_run(q.question)
        d.add_paragraph(f"Зачем: {q.why}" + (f" Риск: {q.risk}" if q.risk else ""))
        if q.options:
            d.add_paragraph("Варианты: " + " / ".join(q.options))
        if q.answer:
            d.add_paragraph(f"Ответ ({q.status}): {q.answer}")

    d.add_heading("6. Итог и что исправить в первую очередь", 1)
    d.add_paragraph(READY[r.readiness]).runs[0].bold = True
    for pr in r.priorities:
        d.add_paragraph(pr, style="List Number")
    foot = d.add_paragraph(f"{PRODUCT_NAME} · LÜMEN Core {__version__} · отчёт сформирован агентом автоматически")
    foot.alignment = WD_ALIGN_PARAGRAPH.CENTER
    buf = io.BytesIO()
    d.save(buf)
    return buf.getvalue()


# =========================================================================== XLSX
def render_xlsx(r: AuditResult) -> bytes:
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill

    wb = Workbook()
    head_fill = PatternFill("solid", fgColor="0E1A33")

    def sheet(ws, header: list[str], rows: list[list], widths: list[int]):
        ws.append(header)
        for c in ws[1]:
            c.font = Font(bold=True, color="FFFFFF")
            c.fill = head_fill
            c.alignment = Alignment(vertical="center", wrap_text=True)
        for row in rows:
            ws.append(row)
        for i, w in enumerate(widths, start=1):
            ws.column_dimensions[ws.cell(row=1, column=i).column_letter].width = w
        for row in ws.iter_rows(min_row=2):
            for c in row:
                c.alignment = Alignment(vertical="top", wrap_text=True)
        ws.freeze_panes = "A2"
        if rows:
            ws.auto_filter.ref = ws.dimensions

    ws = wb.active
    ws.title = "Сводка"
    s = r.scores
    rows = [["Готовность", r.readiness], ["Обоснование", r.readiness_reason], ["Индекс качества", s.quality_index],
            ["Требований", s.total_requirements], ["Замечаний", s.findings_total],
            *[[k, s.by_severity[k]] for k in SEV_HEX], ["Противоречий", s.contradictions],
            ["Непроверяемых", s.unverifiable], ["Неполных", s.incomplete], ["Открытых вопросов", s.open_questions],
            *[[k, v] for k, v in _passport_rows(r)]]
    sheet(ws, ["Показатель", "Значение"], rows, [26, 90])

    amap = {a.req_id: a for a in r.assessments}
    sheet(wb.create_sheet("Требования"),
          ["ID", "ID в документе", "Тип", "Раздел", "Строки", "Стр.", "Балл", "Вердикт", "Краткая формулировка", "Цитата"],
          [[x.id, x.source_id if x.source_id_kind == "explicit" else "", TYPE_RU.get(x.type, x.type), x.section,
            f"{x.loc.line_start}–{x.loc.line_end}", x.loc.page or "", amap[x.id].score, amap[x.id].verdict, x.summary, x.quote]
           for x in r.requirements], [10, 14, 18, 28, 10, 6, 7, 9, 45, 70])
    ws_f = wb.create_sheet("Дефекты")
    sheet(ws_f, ["ID", "Критичность", "Статус", "Уровень", "Требования", "Критерий", "Основание", "Где", "Заголовок",
                 "Цитата", "Что не так", "Риск", "Как исправить", "Улучшенная формулировка", "Источник"],
          [[f.id, f.severity, "подтверждено" if f.status == "confirmed" else "требует проверки",
            "требование" if f.scope == "requirement" else "набор", ", ".join(f.req_ids), criterion_name(f.criterion),
            f.standard_ref, _where(f), f.title, f.quote, f.problem, f.risk, f.fix, f.rewrite, f.source]
           for f in r.findings], [8, 11, 14, 11, 14, 20, 22, 26, 34, 50, 50, 36, 40, 40, 10])
    for row in ws_f.iter_rows(min_row=2):
        sev = row[1].value
        if sev in SEV_HEX:
            row[1].font = Font(bold=True, color=SEV_HEX[sev])
    sheet(wb.create_sheet("Вопросы"), ["ID", "Статус", "Требования", "Вопрос", "Зачем", "Риск", "Варианты", "Ответ"],
          [[q.id, q.status, ", ".join(q.req_ids), q.question, q.why, q.risk, " / ".join(q.options), q.answer]
           for q in r.questions], [8, 11, 14, 50, 40, 34, 40, 34])
    sheet(wb.create_sheet("FinTech"), ["Аспект", "Применимость", "Статус", "Требования", "Комментарий", "Рекомендация"],
          [[c.aspect, c.applicable, c.status, ", ".join(c.req_ids), c.note, c.recommendation] for c in r.fintech],
          [34, 13, 12, 16, 60, 50])
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


