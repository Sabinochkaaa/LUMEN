def render(r: AuditResult, fmt: str) -> bytes:
    from .render import render_html, render_markdown

    if fmt == "md":
        return render_markdown(r).encode("utf-8")
    if fmt == "html":
        return render_html(r).encode("utf-8")
    if fmt == "json":
        return r.model_dump_json(indent=1).encode("utf-8")
    if fmt == "docx":
        return render_docx(r)
    if fmt == "xlsx":
        return render_xlsx(r)
    if fmt == "pdf":
        return render_pdf(r)
    raise ValueError(f"Неизвестный формат отчёта: {fmt}")


def safe_name(r: AuditResult, fmt: str) -> str:
    base = re.sub(r"[^\w\-]+", "_", os.path.splitext(r.passport.document_name)[0])[:50] or "report"
    return f"lumen_{base}.{fmt}"
