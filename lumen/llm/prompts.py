def chat_prompt(context: str, history: list[tuple[str, str]], question: str) -> str:
    hist = "\n".join(f"{who}: {text}" for who, text in history[-6:])
    return f"""РЕЗУЛЬТАТЫ АУДИТА:
<audit>
{context}
</audit>

ИСТОРИЯ ДИАЛОГА:
{hist or '—'}

ВОПРОС ПОЛЬЗОВАТЕЛЯ:
{question}"""
