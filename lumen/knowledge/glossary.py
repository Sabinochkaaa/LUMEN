def find_terms(text: str) -> list[Term]:
    low = text.lower()
    return [t for t in TERMS if re.search(t.pattern, low)]


def defined_in_document(term: Term, text: str) -> bool:
    """True if the document itself defines the term (glossary section or «X — это …»)."""
    low = text.lower()
    has_glossary = bool(re.search(r"(глоссари|термины и определени|определения терминов|glossary)", low))
    word = term.term.split()[0].lower()[:6]
    if has_glossary and word in low[low.find("глоссари") if "глоссари" in low else 0:][:5000]:
        return True
    return bool(re.search(re.escape(word) + r"\w*\s*(—|-|–)\s*(это|означает)|под\s+«?" + re.escape(word) + r"\w*»?\s+понима", low))


def knowledge_block(text: str, limit: int = 18) -> str:
    """Compact reference for the model: only terms present in this document."""
    found = find_terms(text)[:limit]
    if not found:
        return ""
    lines = [f"- {t.term}: {t.definition}" for t in found]
    return "СПРАВОЧНИК ТЕРМИНОВ LÜMEN (используй как экспертное знание; дефектом считай только то, что видно в документе):\n" + "\n".join(lines)
